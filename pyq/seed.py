"""Load a bundled, pre-validated PYQ bank when the database is empty.

The seed file is generated by ``scripts/export_pyq_seed.py`` from a validated
sync run. It makes UPSC practice work immediately on a fresh free-tier instance
and after a redeploy, before (or even without) the first network sync.
"""

from __future__ import annotations

import gzip
import json
import logging
import os

from flask import current_app

from extensions import db
from models.models import Question

_LOGGER = logging.getLogger(__name__)
MIN_EXISTING_ROWS = 100


def seed_path():
    try:
        return current_app.config.get("PYQ_SEED_PATH", "")
    except RuntimeError:
        return ""


def seed_available():
    path = seed_path()
    return bool(path and os.path.exists(path))


def _read_seed(path):
    opener = gzip.open if path.endswith(".gz") else open
    with opener(path, "rt", encoding="utf-8") as handle:
        payload = json.load(handle)
    if isinstance(payload, dict):
        payload = payload.get("questions", [])
    if not isinstance(payload, list):
        raise ValueError("Seed file must contain a list of questions")
    return payload


def seed_bank(force=False):
    """Insert missing seed rows. Existing rows are never overwritten."""
    try:
        if not current_app.config.get("PYQ_SEED_ENABLED", True):
            return 0
        path = seed_path()
        if not path or not os.path.exists(path):
            return 0
        if not force:
            existing = Question.query.filter(
                Question.stage.in_(("prelims", "mains")),
                Question.is_public.is_(True),
            ).count()
            if existing >= MIN_EXISTING_ROWS:
                return 0

        records = _read_seed(path)
        existing_ids = {
            row.external_id
            for row in Question.query.with_entities(Question.external_id)
            .filter(Question.external_id.isnot(None))
            .all()
        }
        created = 0
        for record in records:
            if not isinstance(record, dict):
                continue
            external_id = str(record.get("external_id") or "").strip()
            if not external_id or external_id in existing_ids:
                continue
            payload = {
                "exam": record.get("exam") or "UPSC",
                "subject": record.get("subject"),
                "topic": record.get("topic"),
                "question_text": record.get("question_text"),
                "answer_text": record.get("answer_text"),
                "difficulty": record.get("difficulty") or "medium",
                "is_public": True,
                "stage": record.get("stage"),
                "year": record.get("year"),
                "paper": record.get("paper"),
                "options_json": record.get("options_json"),
                "correct_answer": record.get("correct_answer"),
                "source_url": record.get("source_url"),
                "source_name": record.get("source_name"),
                "external_id": external_id,
                "quality_score": record.get("quality_score", 1.0),
                "verification": record.get("verification") or "archive",
            }
            if not payload["question_text"] or not payload["stage"]:
                continue
            db.session.add(Question(**payload))
            existing_ids.add(external_id)
            created += 1
        if created:
            db.session.commit()
            _LOGGER.info("Loaded %s seeded PYQs from %s", created, path)
        return created
    except Exception:  # pragma: no cover - startup must never fail on seed data
        db.session.rollback()
        _LOGGER.exception("Could not load the bundled PYQ seed")
        return 0
